"""Generate a labelled-synthetic layer-1 log, its labels and a scene descriptor for a sport.

    trophy-synth --sport table_tennis --out evals/fixtures/synthetic/table_tennis --name rally_01 --seed 1 --bounces 6

The ball follows parabolic arcs between scripted contact points and bounces (alternating sides), ends with a floor
bounce, and is seen by two pinhole cameras (side-on at the net line, one on each side, mounted high so
height dominates image y) with pixel noise, dropouts and a
confidence per detection. Camera rows carry the exact plane homography. Nothing here is a measurement of anything real.
"""

from __future__ import annotations

import argparse
import json
import math
import random
from dataclasses import dataclass
from pathlib import Path
from typing import Any

G = 9.81
LABEL = "SYNTHETIC: generated by trophy-synth, not a recording"


@dataclass(frozen=True)
class Court:
    sport: str
    length_m: float
    width_m: float
    floor_z_m: float  # relative to the play plane (0 = the ground is the play plane)
    hit_height_m: float
    hit_x_m: float  # where players make contact (|x|)
    flight_s: tuple[float, float]  # min/max flight time per segment
    cams: tuple[tuple[float, float, float], ...]  # camera positions in the field frame


COURTS = {
    "table_tennis": Court(
        "table_tennis", 2.74, 1.525, -0.76, 0.25, 1.45, (0.25, 0.45), ((0.0, -3.0, 2.0), (0.4, 3.1, 2.2))
    ),
    "pickleball": Court("pickleball", 13.41, 6.10, 0.0, 0.9, 6.9, (0.7, 1.1), ((0.0, -9.0, 4.0), (0.5, 9.5, 4.5))),
}


# ---------------------------------------------------------------- linear algebra (3x3, pure python)


def mat_inv3(m: list[list[float]]) -> list[list[float]]:
    a, b, c = m[0]
    d, e, f = m[1]
    g, h, i = m[2]
    det = a * (e * i - f * h) - b * (d * i - f * g) + c * (d * h - e * g)
    if abs(det) < 1e-15:
        raise ValueError("singular")
    return [
        [(e * i - f * h) / det, (c * h - b * i) / det, (b * f - c * e) / det],
        [(f * g - d * i) / det, (a * i - c * g) / det, (c * d - a * f) / det],
        [(d * h - e * g) / det, (b * g - a * h) / det, (a * e - b * d) / det],
    ]


def mat_mul3(a: list[list[float]], b: list[list[float]]) -> list[list[float]]:
    return [[sum(a[r][k] * b[k][c] for k in range(3)) for c in range(3)] for r in range(3)]


def _norm(v: tuple[float, float, float]) -> tuple[float, float, float]:
    n = math.sqrt(sum(x * x for x in v))
    return (v[0] / n, v[1] / n, v[2] / n)


def _cross(a: tuple[float, float, float], b: tuple[float, float, float]) -> tuple[float, float, float]:
    return (a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0])


@dataclass
class PinholeCamera:
    cam_id: str
    pos: tuple[float, float, float]
    target: tuple[float, float, float]
    f_px: float
    w: int
    h: int

    def __post_init__(self) -> None:
        zc = _norm((self.target[0] - self.pos[0], self.target[1] - self.pos[1], self.target[2] - self.pos[2]))
        up = (0.0, 0.0, 1.0)
        xc = _norm(_cross(zc, up))
        yc = _cross(zc, xc)  # points down in the image (y down)
        self.R = [list(xc), list(yc), list(zc)]  # rows: camera axes in world
        self.t = [-sum(self.R[r][k] * self.pos[k] for k in range(3)) for r in range(3)]
        self.K = [[self.f_px, 0.0, self.w / 2], [0.0, self.f_px, self.h / 2], [0.0, 0.0, 1.0]]
        P = mat_mul3(self.K, [[self.R[r][0], self.R[r][1], self.t[r]] for r in range(3)])  # plane z=0 homography
        self.H_field_to_img = P
        self.H_img_to_field = mat_inv3(P)

    def project(self, X: tuple[float, float, float]) -> tuple[float, float] | None:
        xc = [sum(self.R[r][k] * X[k] for k in range(3)) + self.t[r] for r in range(3)]
        if xc[2] <= 0.05:
            return None
        u = self.K[0][0] * xc[0] / xc[2] + self.K[0][2]
        v = self.K[1][1] * xc[1] / xc[2] + self.K[1][2]
        if not (0 <= u < self.w and 0 <= v < self.h):
            return None
        return (u, v)

    def h_flat(self) -> list[float]:
        return [round(v, 10) for row in self.H_img_to_field for v in row]


# ---------------------------------------------------------------- trajectory


def arc(p0: tuple[float, float, float], p1: tuple[float, float, float], T: float, dt: float, t0: float):
    """Parabolic flight from p0 to p1 in T seconds, sampled every dt, yielding (t, (x, y, z))."""
    vx = (p1[0] - p0[0]) / T
    vy = (p1[1] - p0[1]) / T
    vz = (p1[2] - p0[2]) / T + 0.5 * G * T
    t = 0.0
    while t < T - 1e-9:
        yield t0 + t, (p0[0] + vx * t, p0[1] + vy * t, p0[2] + vz * t - 0.5 * G * t * t)
        t += dt


def script_rally(
    court: Court, n_bounces: int, rng: random.Random
) -> tuple[list[tuple[float, tuple[float, float, float]]], list[dict[str, Any]]]:
    """Serve from A: bounce A, bounce B, hit B, bounce A, hit A, ... then a miss onto the floor past the end."""
    pts: list[tuple[float, tuple[float, float, float]]] = []
    labels: list[dict[str, Any]] = []
    half_l = court.length_m / 2
    half_w = court.width_m / 2
    fps_dt = 1.0 / 30.0
    t = 0.0
    sim_dt = fps_dt / 4  # oversample; the camera picks frames

    def rnd_y() -> float:
        return rng.uniform(-half_w * 0.75, half_w * 0.75)

    pos: tuple[float, float, float] = (-court.hit_x_m, rnd_y(), court.hit_height_m)
    side = (
        "A" if court.sport == "table_tennis" else "B"
    )  # table tennis: serve bounces own side first; pickleball: receiver's side
    for i in range(n_bounces):
        sign = -1.0 if side == "A" else 1.0
        bx = sign * rng.uniform(half_l * 0.25, half_l * 0.9)
        target = (bx, rnd_y(), 0.0)
        T = rng.uniform(*court.flight_s)
        pts += list(arc(pos, target, T, sim_dt, t))
        t += T
        labels.append(
            {
                "t_game_s": round(t, 4),
                "side": side,
                "surface": "table" if court.sport == "table_tennis" else "court",
                "pos_m": {"x": round(bx, 3), "y": round(target[1], 3)},
            }
        )
        pos = target
        if court.sport == "table_tennis" and i == 0:
            side = "B"  # the serve's second bounce is on the receiver's side; no hit in between
            continue
        # the player on this side returns it from beyond the end line
        hit = (sign * court.hit_x_m, rnd_y(), court.hit_height_m)
        T = rng.uniform(*court.flight_s) * 0.6
        pts += list(arc(pos, hit, T, sim_dt, t))
        t += T
        pos = hit
        side = "B" if side == "A" else "A"
    # the final return is missed: it sails past the far end and bounces on the floor
    sign = -1.0 if side == "A" else 1.0
    floor_pt = (sign * (half_l + 0.9), rnd_y(), court.floor_z_m)
    T = rng.uniform(*court.flight_s) * 1.3
    pts += list(arc(pos, floor_pt, T, sim_dt, t))
    t += T
    labels.append(
        {
            "t_game_s": round(t, 4),
            "side": side,
            "surface": "floor",
            "pos_m": {"x": round(floor_pt[0], 3), "y": round(floor_pt[1], 3)},
        }
    )
    # a short roll after the floor bounce, then nothing
    pts += [
        (t + k * sim_dt, (floor_pt[0] + sign * 0.3 * k * sim_dt, floor_pt[1], court.floor_z_m + 0.02))
        for k in range(1, 8)
    ]
    return pts, labels


def generate(
    sport: str, out: Path, name: str, seed: int, n_bounces: int, game_id: str = "g_synth001"
) -> dict[str, Any]:
    court = COURTS[sport]
    rng = random.Random(seed)
    fps = 30.0
    cams = [
        PinholeCamera(
            "c_syn001", court.cams[0], (0.0, 0.0, 0.1), 900.0 if sport == "table_tennis" else 1100.0, 1280, 720
        ),
        PinholeCamera(
            "c_syn002", court.cams[1], (0.0, 0.0, 0.1), 900.0 if sport == "table_tennis" else 1100.0, 1280, 720
        ),
    ]
    pts, bounce_labels = script_rally(court, n_bounces, rng)
    out.mkdir(parents=True, exist_ok=True)
    lines: list[str] = []
    now_ms = 1_750_000_000_000
    for cam in cams:
        calib = {
            "schema": "trophy.calibration.v1",
            "game_id": game_id,
            "cam_id": cam.cam_id,
            "sport": sport,
            "created_at_ms": now_ms,
            "image_size": {"w": cam.w, "h": cam.h},
            "method": "synthetic-pinhole",
            "H_img_to_field": cam.h_flat(),
            "camera_position_m": list(cam.pos),
            "reproj_err_px": 0.0,
            "trusted": True,
            "warnings": [LABEL],
            "solver": "trophy-synth",
        }
        row = {
            "cam_id": cam.cam_id,
            "game_id": game_id,
            "label": f"{LABEL} ({cam.cam_id})",
            "role": "cam",
            "device": {"synthetic": True},
            "calibration": calib,
            "calib_trusted": True,
            "connected": True,
            "fps_in": fps,
            "sync_err_ms": 0.0,
            "last_seen_ms": now_ms,
        }
        lines.append(json.dumps({"table": "camera", "cam_id": cam.cam_id, "row": row}))
    # sample at the camera fps (the sim is oversampled); each camera has its own phase, noise and dropouts
    samples: list[tuple[float, str, dict[str, Any]]] = []
    for ci, cam in enumerate(cams):
        phase = ci * 0.011
        seq = 0
        t_next = phase
        for t, X in pts:
            if t + 1e-9 < t_next:
                continue
            t_next += 1.0 / fps
            seq += 1
            px = cam.project(X)
            if px is None or rng.random() < 0.05:
                row = {"t_game_s": round(t, 4), "seq": seq, "px": None, "conf": 0.0}
            else:
                u = px[0] + rng.gauss(0.0, 1.2)
                v = px[1] + rng.gauss(0.0, 1.2)
                row = {
                    "t_game_s": round(t, 4),
                    "seq": seq,
                    "px": [round(u, 2), round(v, 2)],
                    "conf": round(rng.uniform(0.6, 0.98), 3),
                }
            samples.append((t, cam.cam_id, row))
    samples.sort(key=lambda s: (s[0], s[1]))
    lines += [json.dumps({"table": "ball_sample", "cam_id": c, "row": r}) for _t, c, r in samples]
    (out / f"{name}.l1.jsonl").write_text("\n".join(lines) + "\n", "utf8")
    duration = pts[-1][0] if pts else 0.0
    # the last return sails past the far end: the side that hit it loses, so the receiver of that return wins
    last_surface = [b for b in bounce_labels if b["surface"] != "floor"][-1]["side"]
    labels = {
        "synthetic": True,
        "label": LABEL,
        "sport": sport,
        "labeller": "trophy-synth",
        "rally_winner": "B" if last_surface == "A" else "A",
        "first_server": "A",
        "bounces": bounce_labels,
        "tol_count": 0,
        "tol_t_s": 0.06,
        "tol_pos_m": 0.05,
        "alternate_sides": True,
        "min_recall": 1.0,
        "min_precision": 1.0,
        "expect_ball_dead": True,
    }
    (out / f"{name}.labels.json").write_text(json.dumps(labels, indent=1) + "\n", "utf8")
    scene = {
        "schema": "trophy.scene.v1",
        "game_id": game_id,
        "sport_hint": None,
        "created_at_ms": now_ms,
        "duration_s": round(duration, 3),
        "cameras": [
            {
                "cam_id": c.cam_id,
                "image_size": {"w": c.w, "h": c.h},
                "H_img_to_field": c.h_flat(),
                "reproj_err_px": 0.0,
                "trusted": True,
                "fps": fps,
                "position_m": list(c.pos),
            }
            for c in cams
        ],
        "court": {
            "template": sport,
            "score": 1.0,
            "length_m": court.length_m,
            "width_m": court.width_m,
            "net_x_m": 0.0,
            "candidates": [{"template": sport, "score": 1.0}],
        },
        "ball": {
            "colour": "white" if sport == "table_tennis" else "yellow",
            "radius_px_mean": 5.0 if sport == "table_tennis" else 7.0,
            "radius_px_sd": 1.0,
        },
        "people_count": 2,
        "sample_frames": [],
        "l1_log": f"{name}.l1.jsonl",
        "labels": f"{name}.labels.json",
        "synthetic": True,
        "label": LABEL,
    }
    (out / "scene.json").write_text(json.dumps(scene, indent=1) + "\n", "utf8")
    return {"samples": len(samples), "bounces": len(bounce_labels), "duration_s": duration}


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="trophy-synth", description=__doc__.splitlines()[0])
    ap.add_argument("--sport", choices=sorted(COURTS), required=True)
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--name", default="rally_01")
    ap.add_argument("--seed", type=int, default=1)
    ap.add_argument("--bounces", type=int, default=6, help="surface bounces before the miss")
    a = ap.parse_args(argv)
    info = generate(a.sport, a.out, a.name, a.seed, a.bounces)
    print(json.dumps({"label": LABEL, **info}))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
