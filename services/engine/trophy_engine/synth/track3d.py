"""Generate a labelled-synthetic fused 3D track (track3d.schema.json) with its field and labels.

    trophy-synth3d --out evals/fixtures/synthetic/table_tennis_3d --name game_01 --seed 1 --rallies 8

Each rally follows a scenario (round-robin unless --scenario): a clean rally ending long, a double bounce, an edge
hit (top edge, in), a side-face hit (out), a ball into the net, a serve tossed too low, a serve tossed at an angle.
The ball is held still, tossed, hit, and flies on parabolic arcs; the fused track is sampled at 30 Hz with Gaussian
noise, timing skew and dropouts. Nothing here is a measurement of anything real.
"""

from __future__ import annotations

import argparse
import json
import math
import random
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

G = 9.81
LABEL = "SYNTHETIC: generated by trophy-synth3d, not a recording"
SCENARIOS = ["clean", "double_bounce", "edge_in", "side_face", "net_into", "serve_low", "serve_angle"]


def field_json(sport: str = "table_tennis", sigma: float = 0.012, skew_s: float = 0.006) -> dict[str, Any]:
    hl, hw = 2.74 / 2, 1.525 / 2
    return {
        "schema": "trophy.field.v1",
        "sport": sport,
        "frame": "field",
        "surface_z_m": 0.0,
        "floor_z_m": -0.76,
        "table": {"length_m": 2.74, "width_m": 1.525, "height_m": 0.76},
        "net": {"x_m": 0.0, "height_m": 0.1525, "overhang_m": 0.1525},
        "corners_m": [[-hl, -hw, 0.0], [hl, -hw, 0.0], [hl, hw, 0.0], [-hl, hw, 0.0]],
        "sides": {"A": "x<0", "B": "x>0"},
        "ball": {"diameter_m": 0.040},
        "cameras": [
            {"cam_id": "c_syn001", "position_m": [0.0, -3.0, 2.0], "reproj_err_px": 0.0},
            {"cam_id": "c_syn002", "position_m": [0.4, 3.1, 2.2], "reproj_err_px": 0.0},
        ],
        "uncertainty": {"sigma_default_m": sigma, "sigma_1view_m": 0.03, "skew_sigma_s": skew_s},
        "time": {"sync_method": "synthetic", "skew_sigma_s": skew_s},
        "synthetic": True,
        "label": LABEL,
    }


@dataclass
class Sim:
    """The true trajectory as (t, xyz) at a fine step, plus the labels collected while scripting it."""

    dt: float = 1.0 / 120.0
    t: float = 0.0
    pts: list[tuple[float, tuple[float, float, float]]] = field(default_factory=list)
    bounces: list[dict[str, Any]] = field(default_factory=list)
    contacts: list[dict[str, Any]] = field(default_factory=list)
    nets: list[dict[str, Any]] = field(default_factory=list)
    serves: list[dict[str, Any]] = field(default_factory=list)
    rallies: list[dict[str, Any]] = field(default_factory=list)

    def hold(self, pos, dur, rng, jitter=0.002):
        n = int(round(dur / self.dt))
        for _ in range(n):
            self.pts.append(
                (self.t, (pos[0] + rng.gauss(0, jitter), pos[1] + rng.gauss(0, jitter), pos[2] + rng.gauss(0, jitter)))
            )
            self.t += self.dt

    def arc(self, p0, p1, T):
        """Parabolic flight p0 -> p1 in T s (gravity), appending samples up to (not including) the arrival."""
        vx, vy = (p1[0] - p0[0]) / T, (p1[1] - p0[1]) / T
        vz = (p1[2] - p0[2]) / T + 0.5 * G * T
        k = 0
        while k * self.dt < T - 1e-9:
            tt = k * self.dt
            self.pts.append((self.t + tt, (p0[0] + vx * tt, p0[1] + vy * tt, p0[2] + vz * tt - 0.5 * G * tt * tt)))
            k += 1
        self.t += T

    def gap(self, dur):
        self.t += dur


def hl() -> float:
    return 2.74 / 2


def script_rally(sim: Sim, rally_no: int, server: str, scenario: str, rng: random.Random) -> dict[str, Any]:
    sgn = -1.0 if server == "A" else 1.0  # server's end is at x = sgn * half_l
    recv = "B" if server == "A" else "A"
    ry = lambda: rng.uniform(-0.5, 0.5)  # noqa: E731
    hand = (sgn * (hl() + 0.15), ry(), 0.25)
    sim.hold(hand, rng.uniform(0.6, 0.9), rng)
    t_release = sim.t
    # the toss: height h, angle a from vertical (same on the way down), back to the release height
    if scenario == "serve_low":
        h, ang = rng.uniform(0.06, 0.10), math.radians(rng.uniform(3, 10))
    elif scenario == "serve_angle":
        h, ang = rng.uniform(0.20, 0.28), math.radians(rng.uniform(40, 55))
    else:
        h, ang = rng.uniform(0.18, 0.30), math.radians(rng.uniform(2, 12))
    t_up = math.sqrt(2 * h / G)
    drift = h * math.tan(ang)
    theta = rng.uniform(0, 2 * math.pi)
    dirx, diry = math.cos(theta), math.sin(theta)  # one unit vector: the toss leans the same way up and down
    apex = (hand[0] + drift * dirx, hand[1] + drift * diry, hand[2] + h)
    sim.arc(hand, apex, t_up)
    contact = (apex[0] + drift * dirx, apex[1] + drift * diry, hand[2])
    sim.arc(apex, contact, t_up)
    t_contact = sim.t
    sim.contacts.append({"t_s": round(t_contact, 4), "side": server, "rally_no": rally_no})
    sim.serves.append(
        {
            "rally_no": rally_no,
            "t_release_s": round(t_release, 4),
            "t_contact_s": round(t_contact, 4),
            "height_m": round(h, 4),
            "angle_deg": round(math.degrees(ang), 2),
            "legal": h > 0.1524 and ang < math.radians(30),
        }
    )
    rally = {
        "rally_no": rally_no,
        "t_start_s": round(t_release, 4),
        "t_contact_s": round(t_contact, 4),
        "server_side": server,
        "winner": None,
        "let": False,
        "end_reason": None,
        "scenario": scenario,
    }

    def bounce(x, y, surface="table", side=None, margin=None, line=None):
        sim.bounces.append(
            {
                "t_s": round(sim.t, 4),
                "rally_no": rally_no,
                "side": side or ("A" if x < 0 else "B"),
                "surface": surface,
                "pos_m": [round(x, 4), round(y, 4), 0.0 if surface != "floor" else -0.76],
                **(
                    {"in": margin is not None and margin >= 0, "margin_m": round(margin, 4), "line": line}
                    if margin is not None
                    else {}
                ),
            }
        )

    def roll(fl, dsgn):
        # the ball bounces on along the floor for a moment after landing
        sim.arc(fl, (fl[0] + dsgn * 0.35, fl[1], -0.76), 0.28)
        sim.arc((fl[0] + dsgn * 0.35, fl[1], -0.76), (fl[0] + dsgn * 0.5, fl[1], -0.76), 0.14)

    pos = contact
    # serve: own side bounce, then the receiver's side
    b1 = (sgn * rng.uniform(0.45, 0.9), ry(), 0.0)
    sim.arc(pos, b1, rng.uniform(0.28, 0.36))
    bounce(b1[0], b1[1], side=server)
    b2 = (-sgn * rng.uniform(0.45, 0.9), ry(), 0.0)
    sim.arc(b1, b2, 0.48)  # clears the net (apex ~0.28 m)
    bounce(b2[0], b2[1], side=recv)
    pos = b2
    hitter, other = recv, server
    hsgn = -sgn  # the hitter's end sign
    if scenario in ("serve_low", "serve_angle"):
        # the fault was called at contact; the rest of the serve still happens, then the ball is caught
        catch = (hsgn * (hl() + 0.3), ry(), 0.2)
        sim.arc(pos, catch, 0.3)
        sim.contacts.append({"t_s": round(sim.t, 4), "side": hitter, "rally_no": rally_no})
        sim.hold(catch, 0.4, rng)
        rally.update(winner=hitter, end_reason="stopped", t_end_s=round(sim.t, 4))  # the receiver wins a serve fault
        sim.rallies.append(rally)
        return rally
    n_shots = {
        "clean": rng.randint(2, 4),
        "double_bounce": rng.randint(1, 3),
        "edge_in": rng.randint(1, 3),
        "side_face": rng.randint(1, 3),
        "net_into": rng.randint(1, 3),
    }[scenario]
    for _ in range(n_shots):
        hit = (hsgn * (hl() + 0.12), ry(), 0.28)
        sim.arc(pos, hit, rng.uniform(0.2, 0.3))
        sim.contacts.append({"t_s": round(sim.t, 4), "side": hitter, "rally_no": rally_no})
        tgt = (-hsgn * rng.uniform(0.4, 1.0), ry(), 0.0)
        sim.arc(hit, tgt, rng.uniform(0.42, 0.5))
        bounce(tgt[0], tgt[1], side=other)
        pos = tgt
        hitter, other, hsgn = other, hitter, -hsgn
    # the finishing shot by `hitter` toward `other`'s side
    tsgn = -hsgn
    hit = (hsgn * (hl() + 0.12), ry(), 0.28)
    if scenario != "side_face":
        sim.arc(pos, hit, rng.uniform(0.2, 0.3))
        sim.contacts.append({"t_s": round(sim.t, 4), "side": hitter, "rally_no": rally_no})
    if scenario == "clean":
        # long: sails past the far end and lands on the floor
        fl = (tsgn * (hl() + rng.uniform(0.5, 1.0)), ry(), -0.76)
        sim.arc(hit, fl, rng.uniform(0.55, 0.7))
        bounce(fl[0], fl[1], surface="floor", side=other)
        roll(fl, tsgn)
        rally.update(winner=other, end_reason="floor")
    elif scenario == "double_bounce":
        b = (tsgn * rng.uniform(0.3, 0.6), ry(), 0.0)
        sim.arc(hit, b, 0.45)
        bounce(b[0], b[1], side=other)
        b2 = (tsgn * (abs(b[0]) + 0.35), b[1] + rng.uniform(-0.1, 0.1), 0.0)
        sim.arc(b, b2, 0.2)
        bounce(b2[0], b2[1], side=other)
        fl = (tsgn * (hl() + 0.5), b2[1], -0.76)
        sim.arc(b2, fl, 0.45)
        bounce(fl[0], fl[1], surface="floor", side=other)
        roll(fl, tsgn)
        rally.update(winner=hitter, end_reason="floor")
    elif scenario == "edge_in":
        m = rng.choice([0.006, 0.01, 0.015, 0.02])
        y = ry()
        b = (tsgn * (hl() - m), y, 0.0)
        sim.arc(hit, b, 0.46)
        bounce(b[0], b[1], side=other, margin=m, line="end_A" if tsgn < 0 else "end_B")
        # it kicks off the edge, low and long, to the floor; the returner cannot reach it
        fl = (tsgn * (hl() + 0.9), y, -0.76)
        sim.arc(b, fl, 0.5)
        bounce(fl[0], fl[1], surface="floor", side=other)
        roll(fl, tsgn)
        rally.update(winner=hitter, end_reason="floor")
    elif scenario == "side_face":
        # the hitter is wide, alongside the table; the ball drops past the side line and clips the face below the
        # top: it kicks back out (y reverses) and down to the floor. Out.
        m = rng.choice([0.004, 0.006, 0.008])
        ysgn = rng.choice([-1.0, 1.0])
        hw = 1.525 / 2
        hit = (hsgn * (hl() + 0.12), ysgn * (hw + 0.45), 0.32)
        sim.arc(pos, hit, rng.uniform(0.2, 0.3))
        sim.contacts.append({"t_s": round(sim.t, 4), "side": hitter, "rally_no": rally_no})
        face = (tsgn * rng.uniform(0.3, 1.0), ysgn * (hw + m), -0.012)
        sim.arc(hit, face, 0.5)
        bounce(
            face[0], face[1], surface="side_face", side=other, margin=-m, line="side_left" if ysgn > 0 else "side_right"
        )
        fl = (face[0] + tsgn * 0.1, ysgn * (hw + 0.35), -0.76)
        sim.arc(face, fl, 0.32)
        bounce(fl[0], fl[1], surface="floor", side=other)
        roll(fl, tsgn)
        rally.update(winner=other, end_reason="floor")
    elif scenario == "net_into":
        y = ry()
        netp = (-hsgn * 0.012, y, 0.09)  # hits the net below the cord, from the hitter's side
        sim.arc(hit, netp, 0.3)
        sim.nets.append({"t_s": round(sim.t, 4), "kind": "into", "from_side": hitter, "rally_no": rally_no})
        back = (hsgn * rng.uniform(0.2, 0.5), y, 0.0)
        sim.arc(netp, back, 0.3)
        bounce(back[0], back[1], side=hitter)
        hop = (back[0] + hsgn * 0.25, y, 0.0)
        sim.arc(back, hop, 0.24)  # the rebound (apex ~7 cm)
        bounce(hop[0], hop[1], side=hitter)
        edge = (hsgn * (hl() + 0.06), y, -0.05)  # a smaller rebound carries it off the end
        sim.arc(hop, edge, 0.2)
        fl = (hsgn * (hl() + 0.45), y, -0.76)
        sim.arc(edge, fl, 0.33)
        bounce(fl[0], fl[1], surface="floor", side=hitter)
        roll(fl, hsgn)
        rally.update(winner=other, end_reason="floor")
    # the ball rolls on the floor for a moment, then is picked up (no samples)
    rally["t_end_s"] = round(sim.bounces[-1]["t_s"], 4) if rally["end_reason"] == "floor" else round(sim.t, 4)
    sim.rallies.append(rally)
    return rally


def sample_track(
    sim: Sim, rng: random.Random, fps: float, sigma: float, skew_s: float, dropout: float
) -> list[dict[str, Any]]:
    rows = []
    t_next = sim.pts[0][0] if sim.pts else 0.0
    i = 0
    n = len(sim.pts)
    while i < n:
        t, _ = sim.pts[i]
        if t + 1e-9 < t_next:
            i += 1
            continue
        if t - t_next > 0.03:
            # nobody sees the ball here (it is being picked up): no sample this frame
            t_next += 1.0 / fps
            continue
        # the fused sample for the frame at t_next: the true position at a skewed time, plus noise
        t_true = t_next + rng.gauss(0, skew_s)
        # find the true point at t_true (linear between the fine samples)
        j = i
        while j + 1 < n and sim.pts[j + 1][0] <= t_true:
            j += 1
        if j + 1 < n and sim.pts[j + 1][0] - sim.pts[j][0] > 1e-9 and sim.pts[j + 1][0] - sim.pts[j][0] < 0.05:
            u = (t_true - sim.pts[j][0]) / (sim.pts[j + 1][0] - sim.pts[j][0])
            u = max(0.0, min(1.0, u))
            p0, p1 = sim.pts[j][1], sim.pts[j + 1][1]
            x, y, z = (p0[k] + u * (p1[k] - p0[k]) for k in range(3))
        else:
            x, y, z = sim.pts[j][1]
        if rng.random() >= dropout:
            rows.append(
                {
                    "t_s": round(t_next, 4),
                    "xyz_m": [
                        round(x + rng.gauss(0, sigma), 4),
                        round(y + rng.gauss(0, sigma), 4),
                        round(z + rng.gauss(0, sigma), 4),
                    ],
                    "sigma_m": round(sigma, 4),
                    "conf": round(rng.uniform(0.6, 0.98), 3),
                    "n_views": 2,
                }
            )
        t_next += 1.0 / fps
    return rows


def generate(
    out: Path,
    name: str,
    seed: int,
    n_rallies: int,
    scenario: str | None = None,
    fps: float = 30.0,
    sigma: float = 0.012,
    skew_s: float = 0.006,
    dropout: float = 0.03,
) -> dict[str, Any]:
    rng = random.Random(seed)
    sim = Sim()
    points = {"A": 0, "B": 0}
    for k in range(n_rallies):
        sc = scenario or SCENARIOS[k % len(SCENARIOS)]
        # the engine's rotation (rules.yaml scoring: serves_per_turn 2, alternate every point from 10-10)
        total = points["A"] + points["B"]
        turn = total if (points["A"] >= 10 and points["B"] >= 10) else total // 2
        server = "A" if turn % 2 == 0 else "B"
        r = script_rally(sim, k + 1, server, sc, rng)
        if r.get("winner"):
            points[r["winner"]] += 1
        sim.gap(rng.uniform(1.4, 2.2))  # the ball is picked up: no samples
    rows = sample_track(sim, rng, fps, sigma, skew_s, dropout)
    out.mkdir(parents=True, exist_ok=True)
    fld = field_json(sigma=sigma, skew_s=skew_s)
    (out / "field.json").write_text(json.dumps(fld, indent=1) + "\n", "utf8")
    (out / f"{name}.track3d.jsonl").write_text("\n".join(json.dumps(r) for r in rows) + "\n", "utf8")
    labels = {
        "synthetic": True,
        "label": LABEL,
        "sport": "table_tennis",
        "labeller": "trophy-synth3d",
        "first_server": "A",
        "rallies": sim.rallies,
        "bounces": sim.bounces,
        "contacts": sim.contacts,
        "nets": sim.nets,
        "serves": sim.serves,
        "tol": {
            "t_s": 0.06,
            "t_start_s": 0.2,
            "t_end_s": 0.6,
            "pos_m": 0.05,
            "height_m": 0.03,
            "angle_deg": 10.0,
            "min_recall": 1.0,
            "min_precision": 0.9,
        },
    }
    (out / f"{name}.labels3d.json").write_text(json.dumps(labels, indent=1) + "\n", "utf8")
    return {
        "samples": len(rows),
        "rallies": len(sim.rallies),
        "bounces": len(sim.bounces),
        "duration_s": round(sim.t, 2),
    }


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="trophy-synth3d", description=__doc__.splitlines()[0])
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--name", default="game_01")
    ap.add_argument("--seed", type=int, default=1)
    ap.add_argument("--rallies", type=int, default=7)
    ap.add_argument("--scenario", choices=SCENARIOS, default=None)
    ap.add_argument("--sigma", type=float, default=0.012)
    ap.add_argument("--skew-s", type=float, default=0.006)
    ap.add_argument("--dropout", type=float, default=0.03)
    a = ap.parse_args(argv)
    info = generate(a.out, a.name, a.seed, a.rallies, a.scenario, sigma=a.sigma, skew_s=a.skew_s, dropout=a.dropout)
    print(json.dumps({"label": LABEL, **info}))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
