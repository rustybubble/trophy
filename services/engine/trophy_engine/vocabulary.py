"""The rule pack's vocabulary, rendered from the code that defines it (never a hand-maintained list).

    python -m trophy_engine.vocabulary --module sports/table_tennis > events.md

What a `rules.yaml` `when:` may reference: the layer-2 events the engine consumes (`ev.*`, from
packages/contracts/event.schema.json plus the measurements the engine derives per event), the rally state
(`rally.*`, from trophy_engine.rally.RALLY_FIELDS), the game view (`game.*`), the pack's own `params.*`, and the CEL
functions the engine registers. The Droid gets this file in its sandbox so it encodes laws against what perception
can actually measure, and declines the rest (D-18: perception measures, packs decide).
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

from .rally import RALLY_FIELDS, RallyState
from .rules.cel import FUNCTIONS
from .sportmod.loader import CONTRACTS, load_module

# event types the 2D/3D pipelines produce today, with the payload definition each carries
EVENT_PAYLOADS = {
    "bounce": "BouncePayload",
    "contact": "ContactPayload",
    "net": "NetPayload",
    "ball_dead": "BallDeadPayload",
    "serve_toss": "ServeTossPayload",
    "serve_hidden": "ServeHiddenPayload",
    "serve_position": "ServePositionPayload",
}

# measurements the engine adds to every event before the rules see it (engine._enrich)
ENGINE_EVENT_FIELDS = {
    "n_cams": "number of cameras that saw the event (len(ev.cams))",
    "side_p": "bounce only: P(the bounce was on the side it was given) = Phi(|x - net_x| / sigma_m); "
    "1 when no position",
}

ENGINE_PARAMS = {
    "evidence_min_cams": "with evidence_min_conf: a bounce or net seen by fewer cameras than this AND with conf below "
    "evidence_min_conf never reaches the rules or the rally state (an observation only)",
    "evidence_min_conf": "see evidence_min_cams; both must be set for the policy to apply",
}

GAME_FIELDS = {
    "status": "lobby | live | ended",
    "rally_no": "rallies opened so far",
    "points": "map side -> points in the current game, e.g. game.points.A",
    "games": "map side -> games won",
    "server_side": "who serves next per the scoring params",
    "game_point_for": "sides at game point",
    "match_point_for": "sides at match point",
}

EVENT_BASE = {
    "type": "bounce | contact | net | ball_dead | serve_toss | ...",
    "t_game_s": "game time of the event (seconds)",
    "side": "A | B: the side the event belongs to (bounce: where it landed; contact: the hitter; net: from_side)",
    "conf": "0-1 detector confidence (bounce: fused over cameras)",
    "cams": "camera ids that saw it",
    "pos_m": "bounce: {x, y, z} metres in the field frame (origin at the table centre, +x toward side B, "
    "net plane x = 0)",
    "sigma_m": "bounce: 1-sigma position uncertainty (metres)",
    "payload": "per-type fields, below",
}


def _schema_defs() -> dict[str, Any]:
    return json.loads((CONTRACTS / "event.schema.json").read_text("utf8")).get("$defs", {})


def _prop_line(name: str, spec: dict[str, Any], required: set[str]) -> str:
    kind = spec.get("type") or ("enum" if "enum" in spec else ("ref" if "$ref" in spec else "object"))
    if "enum" in spec:
        kind = " | ".join(str(v) for v in spec["enum"])
    elif "$ref" in spec:
        kind = spec["$ref"].rsplit("/", 1)[-1]
    elif "anyOf" in spec:
        kind = " or ".join(x.get("$ref", x.get("type", "?")).rsplit("/", 1)[-1] for x in spec["anyOf"])
    desc = spec.get("description", "")
    req = "" if name in required else " (optional)"
    return f"  - `payload.{name}`: {kind}{req}{(': ' + desc) if desc else ''}"


def render(module_dir: Path) -> str:
    mod = load_module(module_dir, import_code=False)
    defs = _schema_defs()
    out: list[str] = []
    out.append(f"# Vocabulary for `{mod.sport}` rule packs (generated by `trophy_engine.vocabulary`)")
    out.append("")
    out.append(
        "A rule's `when:` is a CEL expression over `ev`, `rally`, `game` and `params`. Everything below is a "
        "measurement the engine can supply today; a law that needs anything else is not encodable yet and must be "
        "listed as such, never approximated with a field that does not carry that information."
    )
    out.append("")
    out.append("## `ev.*`: the event being judged")
    for k, v in EVENT_BASE.items():
        out.append(f"- `ev.{k}`: {v}")
    for k, v in ENGINE_EVENT_FIELDS.items():
        out.append(f"- `ev.{k}`: {v} (derived by the engine)")
    out.append("")
    out.append("### Payloads by event type")
    for ev_type, def_name in EVENT_PAYLOADS.items():
        d = defs.get(def_name) or {}
        out.append(f"- `ev.type == '{ev_type}'`" + (f": {d['description']}" if d.get("description") else ""))
        req = set(d.get("required") or [])
        for name, spec in (d.get("properties") or {}).items():
            out.append(_prop_line(name, spec, req))
    out.append("")
    out.append(
        "Only `bounce`, `contact`, `net` and `ball_dead` are produced by the two-camera 2D pipeline; `serve_toss`, "
        "`serve_hidden` and `serve_position` need the fused 3D track (not every setup has one). A `net` from the 2D "
        "pipeline is `kind: into` only (a reversal at the net plane); `kind: touch` needs the 3D track."
    )
    out.append("")
    out.append("## `rally.*`: the rally so far (state BEFORE this event is applied)")
    view_keys = list(RallyState(rally_no=1, server_side="A", t_start_s=0.0).view(0.0).keys())
    for k in view_keys:
        out.append(f"- `rally.{k}`: {RALLY_FIELDS.get(k, '(undocumented)')}")
    out.append("")
    out.append("## `game.*`")
    for k, v in GAME_FIELDS.items():
        out.append(f"- `game.{k}`: {v}")
    out.append("")
    out.append("## `params.*`: this pack's `params:` block (editable), plus the engine's evidence policy keys")
    for k, v in sorted((mod.rules.get("params") or {}).items()):
        out.append(f"- `params.{k}` = `{v}`")
    for k, v in ENGINE_PARAMS.items():
        out.append(f"- `params.{k}`: {v}")
    out.append("")
    out.append("## CEL functions")
    for name in sorted(FUNCTIONS):
        out.append(f"- `{name}(...)`")
    out.append("- `has(ev.payload.edge)`: true when the key is present (None values are stripped before evaluation)")
    out.append("- comparisons, `&&`, `||`, `!`, arithmetic on numbers, `size(list)`; strings compare with `==`")
    out.append("")
    out.append("## Rule shape (rulepack.schema.json)")
    out.append(
        "`id` (snake_case), `name`, `tier` (AUTO | BETA | PLAYERS), `kind` (point | violation | edge_call | info), "
        "`when` (CEL), `check` (code | ensemble), `outcome`, optional `team` (CEL giving the side that wins the "
        "point), "
        "`points: 1`, `text` (<= 80 chars, may use {team}), `speech`, `requires: [<event type>]`, `rule_ref`. "
        "Rules run in order; the first scoring rule that fires (kind point/violation with points, or outcome let) "
        "ends the rally."
    )
    return "\n".join(out) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--module", required=True, type=Path)
    a = ap.parse_args(argv)
    sys.stdout.write(render(a.module))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
